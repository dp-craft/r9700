import { describe, expect, test } from "vitest";
import { format, LogfmtError, parse } from "../src/logfmt";
const col = (f: () => unknown): number => { try { f(); } catch (e) { if (e instanceof LogfmtError) return e.column; throw e; } throw new Error("no throw"); };
describe("parse", () => {
  test("empty", () => expect(parse("")).toEqual({}));
  test("blank", () => expect(parse(" \t  ")).toEqual({}));
  test("bare key", () => expect(parse("a")).toEqual({ a: true }));
  test("empty value", () => expect(parse("a=")).toEqual({ a: "" }));
  test("empty value then key", () => expect(parse("a= b")).toEqual({ a: "", b: true }));
  test("bare value with eq", () => expect(parse("a=b=c")).toEqual({ a: "b=c" }));
  test("tabs and many spaces", () => expect(parse("a=1 \t  b=2\tc")).toEqual({ a: "1", b: "2", c: true }));
  test("quoted", () => expect(parse('a="x y"')).toEqual({ a: "x y" }));
  test("quoted empty", () => expect(parse('a=""')).toEqual({ a: "" }));
  test("escapes", () => expect(parse('a="q\\"b\\\\c\\nd"')).toEqual({ a: 'q"b\\c\nd' }));
  test("quote keeps tab", () => expect(parse('a="x\ty"')).toEqual({ a: "x\ty" }));
  test("repeat last wins", () => expect(parse("a=1 a=2")).toEqual({ a: "2" }));
  test("repeat keeps first order", () => expect(Object.keys(parse("a=1 b=2 a=3"))).toEqual(["a", "b"]));
  test("mid quote in bare stays", () => expect(parse('a=b"c')).toEqual({ a: 'b"c' }));
  test("err empty key col", () => expect(col(() => parse("a=1 =x"))).toBe(4));
  test("err unterminated col", () => expect(col(() => parse('a=1 b="xy'))).toBe(6));
  test("err unterminated after escape", () => expect(col(() => parse('b="x\\"'))).toBe(2));
  test("err bad escape col", () => expect(col(() => parse('ab="x\\ty"'))).toBe(5));
  test("err junk after quote col", () => expect(col(() => parse('a="x"y'))).toBe(5));
  test("error type", () => expect(() => parse("=")).toThrow(LogfmtError));
  test("error is Error", () => { try { parse("="); } catch (e) { expect(e).toBeInstanceOf(Error); } });
});
describe("format", () => {
  test("empty", () => expect(format({})).toBe(""));
  test("bare and true", () => expect(format({ a: "1", b: true })).toBe("a=1 b"));
  test("quotes empty", () => expect(format({ a: "" })).toBe('a=""'));
  test("quotes space", () => expect(format({ a: "x y" })).toBe('a="x y"'));
  test("quotes eq", () => expect(format({ a: "x=y" })).toBe('a="x=y"'));
  test("encodes", () => expect(format({ a: 'q"b\\c\nd' })).toBe('a="q\\"b\\\\c\\nd"'));
  test("quotes tab", () => expect(format({ a: "x\ty" })).toBe('a="x\ty"'));
  test("order", () => expect(format({ z: "1", a: "2" })).toBe("z=1 a=2"));
  test("bad key empty", () => expect(col(() => format({ "": "x" }))).toBe(-1));
  test("bad key space", () => expect(col(() => format({ "a b": "x" }))).toBe(-1));
  test("bad key eq", () => expect(col(() => format({ "a=b": "x" }))).toBe(-1));
  test("bad key quote", () => expect(col(() => format({ 'a"b': "x" }))).toBe(-1));
  test("round trip", () => { const x = { a: 'q"b\\c\nd', b: true as const, c: "", d: "x=y", e: "plain" }; expect(parse(format(x))).toEqual(x); });
});
